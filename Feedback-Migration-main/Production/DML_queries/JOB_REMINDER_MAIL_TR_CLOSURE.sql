CREATE PROCEDURE [dbo].[JOB_REMINDER_MAIL_TR_CLOSURE]
AS
BEGIN
 
  
    DECLARE @REQUEST_ID VARCHAR(20)
	DECLARE @APPROVER_ID VARCHAR(20)
	DECLARE @APPROVAL_STATUS VARCHAR(5)
	DECLARE @BODY VARCHAR(MAX)
	DECLARE @APPROVER_NAME VARCHAR(500)
	DECLARE @SUBJECT VARCHAR(200)
	DECLARE @APPLN_NAME VARCHAR(50)
	DECLARE	@EMAIL_PUR VARCHAR(200)
	DECLARE	@SP_NAME VARCHAR(200)
	DECLARE	@EMAIL_PRI INT
	DECLARE	@EMAIL_PROFILE VARCHAR(50)
	DECLARE	@FROMADDR VARCHAR(100)   
	DECLARE	@BLIND_COPY_RECIPIENTS VARCHAR(200)
	DECLARE @TO VARCHAR(MAX)
	DECLARE @CC VARCHAR(MAX)
	DECLARE @HOUR_COUNT INT
	DECLARE @EMPLOYEE_NAME VARCHAR(MAX)
	DECLARE @ADMIN_LOC VARCHAR(20)
	DECLARE @TR VARCHAR(MAX)
	DECLARE @HEAD VARCHAR(MAX)=''
	DECLARE @FOOT VARCHAR(MAX)=''



	SELECT @APPLN_NAME=APPLICATIONNAME, @EMAIL_PUR=EMAIL_PURPOSE,@SP_NAME=STOREDPROCEDURE_NAME,@EMAIL_PRI=EMAIL_PRIORITY,  
		   @EMAIL_PROFILE=PROFILE_NAME,@FROMADDR=FROM_ADDRESS,@BLIND_COPY_RECIPIENTS=BLIND_COPY_RECIPIENTS  
	FROM ADMINDB_EMAIL.DBO.ISG_MAIL_CONFIG   
	WHERE EMAIL_PURPOSE LIKE 'TRAVEL_JOB_REMINDER_MAIL'  AND APPLICATIONNAME='TRAVEL' 


---------------------------------------------------REMINDER MAIL TR CLOSURE-------------------------------------------------------
	SET @TO=''
	SET @CC=''
	SET @BODY=''
	SELECT  * INTO #OPEN_TR FROM(
	SELECT A.S_REQUEST_ID,S_ADMIN_LOC FROM M_TRAVEL_MASTER A INNER JOIN T_TRAVEL_DETAILS B ON A.S_REQUEST_ID=B.S_REQUEST_ID
	WHERE A.S_REQUEST_ID IN (SELECT X.S_REQUEST_ID FROM T_TR_CLOSURE X INNER JOIN T_TR_HISTORY Y ON X.S_REQUEST_ID=Y.S_REQUEST_ID 
							 WHERE S_CLOSURE_STATUS='O' AND S_EDIT_APP_STATUS IN ('A','NA') 
							 AND N_SNO=(SELECT MAX(N_SNO) FROM T_TR_HISTORY WHERE S_REQUEST_ID=X.S_REQUEST_ID))
	AND B.S_TRAVEL_LEG=(SELECT MAX(S_TRAVEL_LEG) FROM T_TRAVEL_DETAILS WHERE S_REQUEST_ID=A.S_REQUEST_ID)
	AND (A.S_APPROVAL_STATUS='A' OR A.S_REQUEST_STATUS='CAN')  and a.S_REQUEST_STATUS <> 'DEL'
	AND CONVERT(DATE,DATEADD(DAY,-1,GETDATE()))>= CONVERT(DATE,CASE WHEN A.B_ONEWAY_CHECK=1 THEN B.D_TRAVEL_DATE
																	WHEN A.B_RETURN_CHECK=1 THEN B.D_RETURN_DATE
																	ELSE (SELECT D_TRAVEL_DATE FROM T_TRAVEL_DETAILS 
																		  WHERE S_REQUEST_ID=A.S_REQUEST_ID 
																		  AND S_TRAVEL_LEG=(SELECT MAX(S_TRAVEL_LEG) 
																							FROM T_TRAVEL_DETAILS WHERE S_REQUEST_ID=A.S_REQUEST_ID))
															  END))T
															  
	SET @HEAD ='<table border="0" cellspacing="1" cellpadding="3" width="97%" ID="Table1" bgcolor="white">'  
	SET @HEAD = @HEAD + '<TR style="color: blue;font-weight:bold; font-family: Verdana; font-size: 11 ;text-align: left"><td>'
	SET @HEAD = @HEAD + '<FONT size="2" color="#000099" face="Arial"><strong>Hi Admin,</strong></FONT><BR>'
	SET @HEAD = @HEAD +'<BR><FONT size="2" color="#b904a6" face="Arial"><strong>Closure for the below TRs have been enabled and the travel date is also crossed. Kindly close the TRs.</strong></FONT></TD></TR>'
	SET @HEAD = @HEAD +'<TR style="color: blue;font-weight:bold; font-family: Verdana; font-size: 11 ;text-align: left"><TD><FONT size="2" color="#b904a6" face="Arial">' 
	
	SET @FOOT = '</FONT></TD></TR><TR><TD><FONT size="2" color="#000099" face="Arial"<strong>Regards'
	SET @FOOT = @FOOT + '<br>StationH Manager</strong></FONT></td></tr></table>'
	
	DECLARE C1 CURSOR FOR SELECT DISTINCT(S_ADMIN_LOC)  FROM #OPEN_TR 
	OPEN C1
	FETCH NEXT FROM C1 INTO @ADMIN_LOC
	WHILE @@FETCH_STATUS!=-1
	BEGIN
		SET @TO=''
		SET @TR='<UL>'
		--@TO
		SELECT @TO= CASE WHEN S_EMPLOYEE_EMAIL IS NULL OR S_EMPLOYEE_EMAIL='' THEN @TO ELSE @TO +';'+ S_EMPLOYEE_EMAIL END
		FROM T_DATA_ACCESS_RESTRICT A INNER JOIN HELIXPRD.dbo.M_EMPLOYEE_EXCHANGE B ON A.S_USER_ID=B.S_EMPLOYEE_ID 
		WHERE A.S_RESTRICT_VALUE=@ADMIN_LOC AND S_USER_ROLE='ADMIN_CLOUSRE'
		--@SUBJECT
		SELECT @SUBJECT='Reminder to close the TR for Location : ' + S_LOCATION  FROM dbo.V_LOCATION_VW WHERE S_LOCATION_ACRONYM=@ADMIN_LOC
		--@TR
		SELECT @TR=CASE WHEN S_REQUEST_ID IS NULL OR S_REQUEST_ID='' THEN @TR
						ELSE @TR+'<LI>'+S_REQUEST_ID+'</LI>' END 
		FROM #OPEN_TR WHERE S_ADMIN_LOC=@ADMIN_LOC
		SET @TR=@TR+'</UL>'
		
		SET @BODY=@HEAD+@TR+@FOOT
		SET @BLIND_COPY_RECIPIENTS=@BLIND_COPY_RECIPIENTS+';'+ 'VinothG@Hexaware.com'

		---SELECT @FROMADDR,@TO,@CC,@SUBJECT,@BODY,@APPLN_NAME,@SP_NAME,@EMAIL_PUR,@EMAIL_PRI,@EMAIL_PROFILE,@BLIND_COPY_RECIPIENTS


		EXEC ADMINDB_EMAIL.DBO.USP_SENDMAIL             
		@FROM =@FROMADDR,                  
		@TO = @TO,   --DYNAMIC     
		@CC= @CC, --DYNAMIC      
		@SUBJECT = @SUBJECT,   --DYNAMIC            
		@BODY =  @BODY, --DYNAMIC      
		@APPLICATIONNAME = @APPLN_NAME,       
		@STOREDPROCEDURE_NAME=@SP_NAME,          
		@EMAIL_PURPOSE = @EMAIL_PUR,      
		@EMAIL_PRIORITY = @EMAIL_PRI,      
		@PROFILE=@EMAIL_PROFILE,      
		@BCC=@BLIND_COPY_RECIPIENTS
		     
		
		FETCH NEXT FROM C1 INTO @ADMIN_LOC
	END
	CLOSE C1
	DEALLOCATE C1
	DROP TABLE #OPEN_TR
---------------------------------------------------REMINDER FOR TICKET EXPIRY-------------------------------------------------------

END