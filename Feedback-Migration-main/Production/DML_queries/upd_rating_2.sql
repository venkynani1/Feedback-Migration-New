
declare @S_EMPLOYEE_ID varchar(20),@Employee_Name varchar(200),@S_SUPERVISOR_ID varchar(20),@S_EMPLOYEE_STATUS_ID varchar(20),@PM_ID varchar(20),@PM_NAME varchar(200),@involvment int

SELECT TOP 1 @PM_ID=A.S_EMPLOYEE_ID,@PM_NAME=LTRIM(rtrim(s_employee_fname))+ ' '+LTRIM(rtrim(S_EMPLOYEE_LNAME)),@involvment=N_INVOLVEMENT FROM RESOURCE_MGMT.DBO.M_EMPLOYEE_ASSIGNMENT A 
			LEFT OUTER JOIN HELIXPRD.DBO.M_EMPLOYEE_EXCHANGE B ON A.S_EMPLOYEE_ID=B.S_EMPLOYEE_ID AND B.S_EMPLOYEE_STATUS_ID='A'
			LEFT OUTER JOIN HelixMaster.DBO.M_GRADE_WEIGHTAGE C ON B.S_GRADE_ID=C.S_GRADE
			WHERE S_ROLE_ID ='PM' 
			AND S_PROJECT_ID=('PRJ-1758')
			AND GETDATE() BETWEEN D_EFFECTIVE_START_DATE AND DATEADD(DAY,1,ISNULL(D_EFFECTIVE_END_DATE,GETDATE()))
			ORDER BY A.N_INVOLVEMENT DESC,C.N_WEIGHTAGE DESC

SELECT  C.N_WEIGHTAGE,* FROM RESOURCE_MGMT.DBO.M_EMPLOYEE_ASSIGNMENT A 
			LEFT OUTER JOIN HELIXPRD.DBO.M_EMPLOYEE_EXCHANGE B ON A.S_EMPLOYEE_ID=B.S_EMPLOYEE_ID AND B.S_EMPLOYEE_STATUS_ID='A'
			LEFT OUTER JOIN HelixMaster.DBO.M_GRADE_WEIGHTAGE C ON B.S_GRADE_ID=C.S_GRADE
			WHERE S_ROLE_ID ='PM' 
			AND S_PROJECT_ID=('PRJ-1758')
			AND GETDATE() BETWEEN D_EFFECTIVE_START_DATE AND DATEADD(DAY,1,ISNULL(D_EFFECTIVE_END_DATE,GETDATE()))
			ORDER BY A.N_INVOLVEMENT DESC,C.N_WEIGHTAGE DESC



Select @PM_ID


